"""
Write docs/frameworks/<baseline>.md (one per catalog baseline) and docs/frameworks/README.md (index) from
catalog/<baseline>.json, profiles/*.json, baselines/*.json, sources/inferred/rule-dispositions.yaml,
sources/inferred/known-findings.yaml and the evidence reports (docs/evidence/*.json). Nothing per framework is
hand-written except the one-line FRAMEWORKS description below. Re-run after rebuilding the catalog, changing a
profile, either register, or collecting evidence (tests/test_framework_docs.py fails while the docs are stale).

Only SGEA-authored or AWS-public fields of the catalog are read (sources, proxy_note, coverage, services,
service_guidance.*.inferred_controls ids). AWS Artifact fields (artifact_sources, crm, cmmc_crm, crm_note,
compliance-guide topics) are never rendered.

Public mode (--public; the default when docs/evidence/ is absent, i.e. in the public distribution built by
tools/make_public.py): no links to files outside the public distribution (evidence reports, sandbox matrix). The
validation status is kept as text; the per-run figures come from sources/inferred/sandbox-validation.json (written by
tools/make_public.py from docs/evidence/*.json) when the reports themselves are absent.

Usage: python3 -I tools/framework_docs.py [--out DIR] [--public | --private]
"""
import argparse, glob, json, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import sgea  # noqa: E402  (resolver: partition / regions / scaffold status, exactly as `sgea list` / `export`)

OUT = os.path.join(ROOT, "docs", "frameworks")

# One neutral line per framework (the only hand-written per-framework text).
FRAMEWORKS = {
    "dod-il2": ("DoD SRG Impact Level 2",
                "DoD Cloud Computing Security Requirements Guide level for public / non-controlled unclassified DoD information."),
    "dod-il4": ("DoD SRG Impact Level 4",
                "DoD Cloud Computing Security Requirements Guide level for Controlled Unclassified Information (CUI)."),
    "dod-il5": ("DoD SRG Impact Level 5",
                "DoD Cloud Computing Security Requirements Guide level for higher-sensitivity CUI and National Security Systems information."),
    "fda-21-cfr-part-11": ("FDA 21 CFR Part 11",
                           "US FDA regulation for trustworthy electronic records and electronic signatures in GxP-regulated work."),
    "fedramp-high": ("FedRAMP High",
                     "US federal cloud authorization baseline for high-impact systems (NIST SP 800-53 Rev 5 High)."),
    "fedramp-low": ("FedRAMP Low",
                    "US federal cloud authorization baseline for low-impact systems (NIST SP 800-53 Rev 5 Low)."),
    "fedramp-moderate": ("FedRAMP Moderate",
                         "US federal cloud authorization baseline for moderate-impact systems (NIST SP 800-53 Rev 5 Moderate)."),
    "hipaa": ("HIPAA Security Rule",
              "US rule for administrative, physical and technical safeguards of electronic protected health information (ePHI)."),
    "hitrust": ("HITRUST CSF",
                "Certifiable control framework that harmonizes HIPAA, NIST and other authorities for healthcare information."),
}

# Coverage statuses in the order tools/build_catalog.py uses ("checked" + DISPOSITIONS).
STATUS_ORDER = ("checked", "implement", "tenant", "not-in-enclave", "customer-prerequisite", "process", "runtime-only")
STATUS_LABEL = {
    "checked": "Enclave-implemented, checked by `sgea check` (Terraform plan and CDK template)",
    "implement": "Enclave-owned, not yet emitted (open gap)",
    "tenant": "Tenant app (service allowed for tenants; the enclave creates none)",
    "not-in-enclave": "Service neither deployed nor allowed (SCP-denied; vacuously compliant)",
    "customer-prerequisite": "Customer prerequisite (landing zone, identity, VPC)",
    "process": "Process (manual evidence, e.g. Audit Manager)",
    "runtime-only": "Runtime-only (observable on the live account; AWS Config evaluates it)",
}
ENGINES = (("terraform", "Terraform"), ("cdk", "CDK"))
OPS = [("Incident response", "../operations/incident-response.md"),
       ("Key and secret management", "../operations/key-and-secret-management.md"),
       ("Change and upgrade", "../operations/change-and-upgrade.md"),
       ("Tenant onboarding", "../operations/tenant-onboarding.md"),
       ("Decommissioning", "../operations/decommissioning.md"),
       ("Access review", "../operations/access-review.md")]
HEADER = "<!-- Generated by tools/framework_docs.py from catalog/, profiles/, sources/inferred/ and docs/evidence/ — do not edit. -->"
PUBLIC_HEADER = "<!-- Generated by tools/framework_docs.py from catalog/, profiles/ and sources/inferred/ — do not edit. -->"
# Sandbox-validation summary (the evidence records load() derives from docs/evidence/*.json), for trees without the reports.
VALIDATION_SUMMARY = os.path.join("sources", "inferred", "sandbox-validation.json")


def public_default(root=ROOT):
    """Public mode unless the evidence reports are present (private repository)."""
    return not os.path.isdir(os.path.join(root, "docs", "evidence"))


def _cell(s):
    return re.sub(r"\s+", " ", str(s if s is not None else "")).replace("|", "\\|").strip()


def _anchor(title):
    """GitHub/GitLab heading anchor."""
    return re.sub(r"[^a-z0-9 _-]", "", title.lower()).replace(" ", "-")


def load(root=ROOT):
    cats = {}
    for f in sorted(glob.glob(os.path.join(root, "catalog", "*.json"))):
        if not os.path.basename(f).startswith("_"):
            d = json.load(open(f))
            cats[d["baseline"]] = d
    bdir = os.path.join(root, "baselines")
    frags = {b: json.load(open(os.path.join(bdir, b + ".json"))) for b in cats}
    profiles = []
    for f in sorted(glob.glob(os.path.join(root, "profiles", "*.json"))):
        if os.path.basename(f).startswith("_"):
            continue
        resolved, prof = sgea.resolve(f, bdir)
        profiles.append({
            "file": os.path.basename(f), "id": resolved["profile"]["id"], "name": resolved["profile"].get("name", ""),
            "baselines": resolved["baselines"], "extends": resolved["profile"]["extends"],
            "partition": resolved.get("partition"), "regions": resolved.get("regions") or {},
            "scaffold": sgea._baseline_status(prof, bdir)})
    evidence = load_evidence(root)
    disp = yaml.safe_load(open(os.path.join(root, "sources", "inferred", "rule-dispositions.yaml"))) or {}
    kf = (yaml.safe_load(open(os.path.join(root, "sources", "inferred", "known-findings.yaml"))) or {}).get("findings") or []
    return cats, frags, profiles, evidence, disp.get("exceptions") or [], kf


def load_evidence(root=ROOT):
    """Per sandbox run: profile, engine, baselines, collected_at, counts, report name. From docs/evidence/*.json, else
    from the summary tools/make_public.py writes (VALIDATION_SUMMARY), else none."""
    reports = sorted(glob.glob(os.path.join(root, "docs", "evidence", "*.json")))
    summary = os.path.join(root, VALIDATION_SUMMARY)
    if not reports and os.path.exists(summary):
        return json.load(open(summary))["runs"]
    evidence = []
    for f in reports:
        d = json.load(open(f))
        obs = d["observations"]
        evidence.append({"profile": d["profile"], "engine": d["engine"], "baselines": d.get("baselines") or [],
                         "collected_at": d["collected_at"], "observed": len(obs),
                         "checked": sum(1 for o in obs if o["meets"] is not None),
                         "meets": sum(1 for o in obs if o["meets"]),
                         "md": os.path.basename(f)[:-5] + ".md"})
    return evidence


def _counts(cov):
    statuses = list(STATUS_ORDER) + sorted({v["status"] for v in cov.values()} - set(STATUS_ORDER))
    return [(s, sum(1 for v in cov.values() if v["status"] == s)) for s in statuses]


def _coverage_anchors(cats):
    """Section anchors of docs/CONTROL-COVERAGE.md (distinct rules per status across all baselines)."""
    allrules = {}
    for c in cats.values():
        for n, v in c["coverage"].items():
            allrules[n] = v["status"]
    return {s: _anchor("%s (%d)" % (s, sum(1 for v in allrules.values() if v == s))) for s in set(allrules.values())}


def _validation(b, frag, evidence):
    engines = sorted({e["engine"] for e in evidence if b in e["baselines"]})
    scaffold = frag.get("_status") == "scaffold-unverified"
    if engines:
        txt = "Sandbox-validated (%s)" % ", ".join(lbl for k, lbl in ENGINES if k in engines)
    else:
        txt = "Not deployment-validated (`sgea verify` / `sgea check` only)"
    return txt + ("; baseline flagged scaffold-unverified (`sgea export` needs `--allow-unverified`)" if scaffold else "")


def _framework_doc(b, cat, frag, profiles, evidence, excs, kf, anchors, public=False):
    name, desc = FRAMEWORKS.get(b, (b, ""))
    cov = cat["coverage"]
    out = [PUBLIC_HEADER if public else HEADER, "", "# %s (`%s`)" % (name, b), "", desc, ""]
    if cat.get("proxy_note"):
        out += ["> " + cat["proxy_note"], ""]

    out += ["## AWS Config conformance packs", "",
            "Pinned to awslabs/aws-config-rules commit `%s`." % cat["conformance_packs_commit"][:12], "",
            "| Pack | Template | Control mapping |", "|---|---|---|"]
    out += ["| %s | [YAML](%s) | [AWS docs](%s) |" % (s["pack"], s["pack_url"], s["control_mapping_url"]) for s in cat["sources"]]

    out += ["", "## Profiles and validation", "",
            "Baseline validation status: **%s**." % _validation(b, frag, evidence), "",
            "| Profile | Composes | How this baseline is used | Partition | Regions (primary; allowed) | Terraform | CDK |",
            "|---|---|---|---|---|---|---|"]
    rows = 0
    for p in profiles:
        if b in p["baselines"]:
            how = "composed: pack deployed, rules checked"
        elif b in p["extends"]:
            how = "settings inherited only (pack not deployed)"
        else:
            continue
        rows += 1
        reg = p["regions"]
        ev = {e["engine"]: e for e in evidence if e["profile"] == p["id"]}
        done = (lambda e: "sandbox-validated (%s)" % e["collected_at"][:10]) if public else \
            (lambda e: "[report](../evidence/%s)" % e["md"])
        cells = [done(ev[k]) if k in ev else ("not deployed (scaffold)" if p["scaffold"] else "not deployed")
                 for k, _ in ENGINES]
        out.append("| `%s` | %s | %s | %s | %s; %s | %s | %s |" % (
            p["file"][:-5], " + ".join(p["baselines"]), how, p["partition"], reg.get("primary", ""),
            ", ".join(reg.get("allowed", [])), cells[0], cells[1]))
    if not rows:
        out.append("| (none) | | | | | | |")

    counts = _counts(cov)
    out += ["", "## Control coverage", "",
            "%d AWS Config rules in the composed pack(s). Every rule is checked by `sgea check` or carries one recorded "
            "disposition (`sources/inferred/rule-dispositions.yaml`). Full list: row `%s` of "
            "[docs/CONTROL-COVERAGE.md](../CONTROL-COVERAGE.md); rules by status:" % (len(cov), b), "",
            "| Status | Meaning | Rules |", "|---|---|---:|"]
    for s, n in counts:
        link = "[`%s`](../CONTROL-COVERAGE.md#%s)" % (s, anchors[s]) if s in anchors else "`%s`" % s
        out.append("| %s | %s | %d |" % (link, STATUS_LABEL.get(s, s), n))
    bexc = [x for x in excs if x["rule"] in cov]
    bkf = [f for f in kf if f["rule"] in cov]
    out += ["", "Also: %d documented exception(s) (NON_COMPLIANT by design) and %d known open finding(s) apply — see "
            "Customer responsibilities." % (len(bexc), sum(1 for f in bkf if f.get("status") == "open"))]
    others = sorted({o for p in profiles if b in p["baselines"] for o in p["baselines"]} - {b})
    if others:
        out += ["", "Profiles composing this baseline also deploy and check the packs of: %s. A deployment's coverage is "
                "the union of those pages." % ", ".join("[%s](%s.md)" % (o, o) for o in others)]

    out += ["", "## What the enclave deploys", "",
            "Both engines emit the same resources: see [README — What the enclave deploys](../../README.md#what-the-enclave-deploys). "
            "Rules of this baseline the enclave implements and `sgea check` verifies, by service:", "",
            "| Service | Checked rules |", "|---|---|"]
    by_svc = {}
    for svc, rules in sorted(cat["services"].items()):
        for r in rules:
            if cov.get(r["config_rule"], {}).get("status") == "checked":
                by_svc.setdefault(svc, []).append(r["config_rule"])
    out += ["| %s | %s |" % (svc, ", ".join("`%s`" % n for n in sorted(ns))) for svc, ns in sorted(by_svc.items())]
    sg = [(svc, v.get("inferred_controls") or []) for svc, v in sorted(cat["service_guidance"].items())]
    sg = [(svc, ics) for svc, ics in sg if ics]
    if sg:
        out += ["", "SGEA's own Bedrock / AgentCore controls (`sources/inferred/service-controls.yaml`, all checked by "
                "`sgea check`; conditional ones apply only when the profile setting is on — e.g. DoD SCCA only with dod-il4 / dod-il5):", "",
                "| Service | SGEA controls | Conditional |", "|---|---:|---:|"]
        out += ["| %s | %d | %d |" % (svc, len(ics), sum(1 for c in ics if c.get("applies_when"))) for svc, ics in sg]

    out += ["", "## Customer responsibilities", ""]
    cust = sorted((n, v) for n, v in cov.items() if v["status"] in ("customer-prerequisite", "process"))
    out += ["### Customer-prerequisite and process rules (%d)" % len(cust), ""]
    if cust:
        out += ["| Rule | Disposition | Reason |", "|---|---|---|"]
        out += ["| `%s` | %s | %s |" % (n, v["status"], _cell(v.get("reason"))) for n, v in cust]
    else:
        out += ["None."]
    ops = sorted((n, v) for n, v in cov.items() if v["status"] in ("tenant", "runtime-only", "implement"))
    if ops:
        out += ["", "### Tenant, runtime-only and open-gap rules (%d)" % len(ops), "",
                "| Rule | Disposition | Reason |", "|---|---|---|"]
        out += ["| `%s` | %s | %s |" % (n, v["status"], _cell(v.get("reason"))) for n, v in ops]
    out += ["", "### Documented exceptions that apply (%d)" % len(bexc), ""]
    if bexc:
        out += ["| Rule | Resource | Reason |", "|---|---|---|"]
        out += ["| `%s` | `%s`%s | %s |" % (x["rule"], x["resource"], " (%s)" % x["owner"] if x.get("owner") else "", _cell(x["reason"]))
                for x in bexc]
    else:
        out += ["None."]
    out += ["", "### Known findings that apply (%d)" % len(bkf), ""]
    if bkf:
        out += ["| Finding | Rule | Owner | Status | What to do / fix |", "|---|---|---|---|---|"]
        out += ["| %s | `%s` | %s | %s | %s |" % (f["id"], f["rule"], f["owner"], f["status"],
                                                 _cell(f.get("customer_action") if f.get("status") == "open" else f.get("fix")))
                for f in bkf]
        if not public:
            out += ["", "Details: [docs/evidence/README.md](../evidence/README.md)."]
    else:
        out += ["None."]

    bev = [e for e in evidence if b in e["baselines"]]
    out += ["", "## Evidence", ""]
    if bev and public:
        out += ["Sandbox deployments of profiles composing this baseline, with the as-deployed configuration recorded "
                "(read-only) and compared to the profile. The reports are not part of this distribution; "
                "`tools/collect_evidence.py` produces them for your own deployment.", "",
                "| Profile | Engine | Collected (UTC) | Settings observed | Checked vs profile | Meet |",
                "|---|---|---|---|---|---:|"]
        out += ["| %s | %s | %s | %d | %d | %d |" % (
            e["profile"], dict(ENGINES)[e["engine"]], e["collected_at"], e["observed"], e["checked"], e["meets"]) for e in bev]
    elif bev:
        out += ["As-deployed configuration reports from sandbox deployments of profiles composing this baseline "
                "(index: [docs/evidence/README.md](../evidence/README.md)):", "",
                "| Profile | Engine | Collected (UTC) | Settings observed | Checked vs profile | Meet | Report |",
                "|---|---|---|---|---|---:|---|"]
        out += ["| %s | %s | %s | %d | %d | %d | [%s](../evidence/%s) |" % (
            e["profile"], dict(ENGINES)[e["engine"]], e["collected_at"], e["observed"], e["checked"], e["meets"], e["md"], e["md"])
            for e in bev]
    else:
        out += ["No sandbox evidence: no profile composing this baseline has been deployed. Verification is "
                "`sgea verify` and `sgea check` on the exported IaC only."]

    out += ["", "## Operations", "",
            "- `MANUAL-STEPS.md` and `OPERATIONS.md` in each `sgea export` (`build/<profile-id>/`): deployment steps outside "
            "the IaC, known-finding actions and day-2 operation for that profile.",
            "- [Deployment prerequisites](../DEPLOYMENT-PREREQUISITES.md)"]
    out += ["- [%s](%s)" % (t, p) for t, p in OPS]
    return "\n".join(out) + "\n"


def _index(cats, frags, profiles, evidence, excs, kf, public=False):
    out = [PUBLIC_HEADER if public else HEADER, "", "# Frameworks", "",
           "One page per SGEA baseline: conformance packs, profiles and validation status, control coverage, customer "
           "responsibilities, evidence and operations. Generated by `tools/framework_docs.py`; the rule-by-rule list is "
           "[docs/CONTROL-COVERAGE.md](../CONTROL-COVERAGE.md).", "",
           "![Four-layer shared responsibility: AWS, the platform team's enclave, each application team and the ISSO / "
           "authorizing official, who determines compliance; SGEA checks the IaC and does not make the system "
           "compliant.](../diagrams/sgea_01_shared_responsibility.png)", "",
           "| Baseline | Framework | Packs | Profiles (composed) | Validation | Rules | Checked | Customer-prerequisite | Process | Open findings |",
           "|---|---|---|---|---|---:|---:|---:|---:|---:|"]
    for b, cat in sorted(cats.items()):
        cnt = dict(_counts(cat["coverage"]))
        profs = [p["file"][:-5] for p in profiles if b in p["baselines"]]
        out.append("| [%s](%s.md) | %s | %s | %s | %s | %d | %d | %d | %d | %d |" % (
            b, b, FRAMEWORKS.get(b, (b,))[0], ", ".join(s["pack"] for s in cat["sources"]),
            ", ".join("`%s`" % p for p in profs) or "-", _validation(b, frags[b], evidence),
            len(cat["coverage"]), cnt.get("checked", 0), cnt.get("customer-prerequisite", 0), cnt.get("process", 0),
            sum(1 for f in kf if f.get("status") == "open" and f["rule"] in cat["coverage"])))
    out += ["", "Status meanings:", ""]
    out += ["- `%s`: %s" % (s, STATUS_LABEL[s]) for s in STATUS_ORDER]
    return "\n".join(out) + "\n"


def render(root=ROOT, public=None):
    """{filename: markdown} for docs/frameworks/. public=None: public_default(root)."""
    if public is None:
        public = public_default(root)
    cats, frags, profiles, evidence, excs, kf = load(root)
    anchors = _coverage_anchors(cats)
    docs = {b + ".md": _framework_doc(b, c, frags[b], profiles, evidence, excs, kf, anchors, public) for b, c in cats.items()}
    docs["README.md"] = _index(cats, frags, profiles, evidence, excs, kf, public)
    return docs


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--root", default=ROOT, help=argparse.SUPPRESS)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--public", dest="public", action="store_true", default=None,
                      help="public-distribution docs (no links to evidence reports / sandbox matrix)")
    mode.add_argument("--private", dest="public", action="store_false", help="docs with evidence-report links")
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    docs = render(args.root, args.public)
    for name, text in sorted(docs.items()):
        with open(os.path.join(args.out, name), "w") as f:
            f.write(text)
    print("%s: %d framework docs + README.md" % (os.path.relpath(args.out, ROOT), len(docs) - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
