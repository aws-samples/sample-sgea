"""
Write docs/evidence/README.md — the customer evidence-pack index — from the collected reports
(docs/evidence/*.json), sources/inferred/known-findings.yaml and the documented exceptions in
sources/inferred/rule-dispositions.yaml. Re-run after collecting evidence or changing either register.

Usage: python3 -I tools/evidence_index.py
"""
import glob, json, os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EV = os.path.join(ROOT, "docs", "evidence")


def main():
    reports = []
    for path in sorted(glob.glob(os.path.join(EV, "*.json"))):
        d = json.load(open(path))
        obs = d["observations"]
        reports.append((d["profile"], "Terraform" if d["engine"] == "terraform" else "CloudFormation (CDK)", d["collected_at"],
                        len(obs), sum(1 for o in obs if o["meets"] is not None), sum(1 for o in obs if o["meets"]),
                        os.path.basename(path)[:-5] + ".md"))
    kf = (yaml.safe_load(open(os.path.join(ROOT, "sources", "inferred", "known-findings.yaml"))) or {}).get("findings") or []
    excs = yaml.safe_load(open(os.path.join(ROOT, "sources", "inferred", "rule-dispositions.yaml"))).get("exceptions") or []

    out = ["# SGEA as-deployed configuration evidence", "",
           "Generated by `tools/evidence_index.py`. What these reports are: for each validated profile and IaC engine, SGEA "
           "deployed the enclave and a sample tenant app into a sandbox account, ran the 9-check end-to-end test, and then "
           "recorded the **live configuration** with read-only AWS API calls (`tools/collect_evidence.py`) before teardown. "
           "Each report lists every observed setting, the value the profile requires, whether it meets it, and the framework "
           "controls it evidences (AWS Config rule names, SGEA control IDs, NIST SP 800-53 families), plus the live AWS Config "
           "conformance-pack results attributed by owner. Account ids are redacted; no secrets, prompts or log contents were read.", "",
           "Use them as implementation evidence for your SSP / assessment package, **next to** your own AWS Config results from "
           "your account (the sandbox is not your system).", "",
           "## Reports", "",
           "| Profile | IaC engine | Collected (UTC) | Settings observed | Checked vs profile | Meet | Report |",
           "|---|---|---|---|---|---|---|"]
    out += ["| %s | %s | %s | %d | %d | %d | [%s](%s) |" % (p, e, w, n, c, m, f, f) for p, e, w, n, c, m, f in reports]
    out += [""]
    if os.path.exists(os.path.join(ROOT, "docs", "SANDBOX-MATRIX.md")):   # written by tools/sandbox_matrix.sh
        out += ["End-to-end results per run (authenticated answer, allowed gateway tool call, PII block, contextual-PII "
                "masking, token metering, over-budget denial, unauthenticated rejection): `docs/SANDBOX-MATRIX.md`.", ""]
    out += ["**Not validated by deployment:** FedRAMP High, DoD IL4, DoD IL5 (AWS GovCloud (US) account required). Their IaC "
            "passes `sgea check` on the synthesized CloudFormation (0 FAIL / 0 GAP) and `terraform validate` only.", "",
            "## How to read a report", "",
            "- **Meets = no** in a report is a deviation. Every deviation in these reports is a known open finding (below), "
            "belongs to the sample tenant app, or was collected before a time-dependent result was recorded as a documented "
            "exception (e.g. `dynamodb-in-backup-plan` in the older HITRUST / Part 11 Terraform reports).",
            "- **Detective controls (live findings)** list what AWS Config reported NON_COMPLIANT at collection time, by owner: "
            "`enclave`, `tenant` (the sample app), `cdk-deploy-helper` (CDK's deployment-time Lambdas), `sandbox-artifact` "
            "(keys of earlier, deleted sandbox runs) and `other` (workloads in the sandbox account outside SGEA). Only "
            "`enclave` and `tenant` findings concern SGEA.",
            "- **documented exception** = NON_COMPLIANT by design, with the reason (table below).",
            "- **stale** = AWS Config's result predates this deployment (resource names repeat across sandbox runs).", ""]
    for title, sel in (("Known open findings (not fixed in this release)", "open"), ("Fixed findings", "fixed")):
        fs = [f for f in kf if f.get("status") == sel]
        if not fs:
            continue
        out += ["## " + title, ""]
        for f in fs:
            out += ["### %s — `%s` (%s)" % (f["id"], f["rule"], f["owner"]), ""]
            if sel == "fixed":
                out += ["- **Fixed:** " + f["fix"], "- **Verified:** " + f["verified"],
                        "- **Reports collected before the fix** still show it: " + f["observed"], ""]
            else:
                out += ["- **Observed:** " + f["observed"], "- **Impact:** " + f["impact"],
                        "- **What to do:** " + f["customer_action"], ""]
    out += ["## Documented exceptions (by design)", "", "| Rule | Resource | Reason |", "|---|---|---|"]
    out += ["| `%s` | `%s`%s | %s |" % (x["rule"], x["resource"], " (%s)" % x["owner"] if x.get("owner") else "", x["reason"]) for x in excs]
    out += ["", "Full rule-by-rule coverage per framework: `docs/CONTROL-COVERAGE.md`. Deployment steps outside the IaC: "
            "`MANUAL-STEPS.md` in each `sgea export`.", ""]
    open(os.path.join(EV, "README.md"), "w").write("\n".join(out))
    print("docs/evidence/README.md: %d reports, %d known findings, %d exceptions" % (len(reports), len(kf), len(excs)))


if __name__ == "__main__":
    main()
