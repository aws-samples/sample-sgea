"""
Manual steps a deployment team must complete outside the emitted IaC, for ONE resolved profile.

Written to <out>/<profile-id>/MANUAL-STEPS.md by `sgea export`. Every item is derived from the resolved
config, the composed packs' parameters (catalog/<baseline>.json) and the rule-disposition register
(sources/inferred/rule-dispositions.yaml), so the list changes with the profile instead of drifting.
"""
import json, os

try:
    from .derived import account_baseline, endpoint_services, policy_engine_available, replica_region, scca_required
except ImportError:  # in-repo fallback import
    from derived import account_baseline, endpoint_services, policy_engine_available, replica_region, scca_required

LAMBDA_QUOTA_CODE = "L-B99A9384"   # Lambda: Concurrent executions
LAMBDA_UNRESERVED_MIN = 100        # Lambda always keeps 100 executions unreserved

# On-demand list prices, us-east-1, from the AWS Price List API (2026-10-21). Estimate only: GovCloud and other
# regions differ; confirm with the AWS Pricing Calculator before quoting.
PRICE_DATE = "2026-10-21"
HOURS_PER_MONTH = 730
VPCE_HOUR = 0.01            # interface endpoint, per AZ-hour (USE1-VpcEndpoint-Hours)
VPCE_GB = 0.01              # interface endpoint data processed, per GB (first 1 PB)
AURORA_ACU_HOUR = 0.12      # Aurora PostgreSQL Serverless v2, per ACU-hour
AURORA_GB_MONTH = 0.10      # Aurora storage, per GB-month
AURORA_MIN_ACU, AURORA_INSTANCES = 0.5, 2   # module defaults (min_acu, instance_count)
KMS_KEY_MONTH = 1.00        # per customer managed key (each automatic rotation adds a key version, capped by KMS)
SECRET_MONTH = 0.40         # Secrets Manager, per secret (Aurora RDS-managed admin password)
CONFIG_EVAL = 0.001         # AWS Config rule evaluation (first 100,000 / month)
CONFIG_ITEM = 0.003         # AWS Config configuration item recorded
CT_DATA_EVENT = 0.000001    # CloudTrail data event (per event)
LOGS_GB = 0.50              # CloudWatch Logs ingestion, per GB (Standard)


def cost_estimate(resolved, azs=2):
    """Fixed monthly floor of the enclave itself (no traffic, no tenant apps) + the usage-priced lines."""
    eps = endpoint_services(resolved)
    allow = resolved["services"]["allow"]
    lines = [("Interface VPC endpoints (%d services x %d AZs)" % (len(eps), azs), len(eps) * azs * VPCE_HOUR * HOURS_PER_MONTH)]
    if "aurora-postgresql" in allow:
        lines.append(("Aurora Serverless v2 at the %.1f-ACU minimum x %d instances" % (AURORA_MIN_ACU, AURORA_INSTANCES),
                      AURORA_MIN_ACU * AURORA_INSTANCES * AURORA_ACU_HOUR * HOURS_PER_MONTH))
        lines.append(("Aurora RDS-managed admin-password secret", SECRET_MONTH))
    lines.append(("KMS customer managed keys (primary + log replica)", 2 * KMS_KEY_MONTH))
    return lines


def enclave_functions(resolved, root):
    """Enclave-owned Lambda functions that carry reserved concurrency (lambda-concurrency-check).
    Same conditions as the emitters: the gateway interceptor exists for token budgets, or for the gateway tool path
    where the AgentCore Policy Engine is not available."""
    agentcore = "bedrock-agentcore" in resolved["services"]["allow"]
    tc = resolved.get("token_control", {}).get("enabled")
    tool_path = "gateway_tool_path" in resolved["guardrails"].get("levels", []) and not policy_engine_available(resolved, root)
    gw_interceptor = agentcore and (tc or tool_path)
    meter = tc and resolved["logging"].get("model_invocation_logging")
    return [n for n, on in (("gateway interceptor", gw_interceptor), ("token meter", meter)) if on]


def lambda_quota_need(resolved, root):
    """(required account concurrency, functions, reserved per function) for lambda-concurrency-check, or None."""
    per = account_baseline(resolved, root)["lambda_reserved_concurrency"]
    fns = enclave_functions(resolved, root)
    if not (per and fns):
        return None
    return len(fns) * per + LAMBDA_UNRESERVED_MIN, fns, per


def _dispositions(root, resolved, kind):
    import yaml
    disp = yaml.safe_load(open(os.path.join(root, "sources", "inferred", "rule-dispositions.yaml")))["dispositions"]
    rules = set()
    for b in resolved["baselines"]:
        cat = json.load(open(os.path.join(root, "catalog", b + ".json")))
        rules |= {r["config_rule"] for lst in cat["services"].values() for r in lst}
    return sorted((n, d["reason"]) for n, d in disp.items() if d["disposition"] == kind and n in rules)


def render(resolved, root, targets):
    pid, part = resolved["profile"]["id"], resolved["partition"]
    primary, replica = resolved["regions"]["primary"], replica_region(resolved)
    ab = account_baseline(resolved, root)
    base = set(resolved["baselines"])
    out = ["# Manual steps — %s" % pid, "",
           "Generated by `sgea export` from the resolved profile, the composed conformance packs and "
           "`sources/inferred/rule-dispositions.yaml`. Complete **section 1 before the first deploy**: these "
           "steps need an AWS request or another account and cannot be done by the IaC.", "",
           "Partition `%s` · primary region `%s` · log replica region `%s` · baselines: %s" % (
               part, primary, replica, ", ".join(resolved["baselines"])), ""]

    # ---------------- 1. before the first deploy ----------------
    out += ["## 1. Before the first deploy (AWS requests / other accounts)", ""]
    n = 1
    quota = lambda_quota_need(resolved, root)
    if quota:
        need, fns, _ = quota
        out += ["%d. **Raise the Lambda concurrent-executions quota to at least %d in `%s`** (AWS Service Quotas "
                "request; may need an AWS Support case and can take days)." % (n, need, primary), "",
                "   - Why: `lambda-concurrency-check` in the composed packs requires reserved concurrency of at least "
                "%d per enclave function (pack parameter `ConcurrencyLimitLow`). The enclave reserves it for %d "
                "function(s) (%s), and Lambda keeps %d executions unreserved: %d x %d + %d = **%d**. The default "
                "quota is 1,000." % (ab["lambda_reserved_concurrency"], len(fns), ", ".join(fns), LAMBDA_UNRESERVED_MIN,
                                     len(fns), ab["lambda_reserved_concurrency"], LAMBDA_UNRESERVED_MIN, need),
                "   - Without it the apply fails when Lambda refuses the reservation; the Terraform root's "
                "`check \"lambda_concurrency_quota\"` block warns at plan time.",
                "   - Request (from the enclave account, `%s`):" % primary, "",
                "     ```bash",
                "     aws service-quotas get-service-quota --service-code lambda --quota-code %s --region %s" % (LAMBDA_QUOTA_CODE, primary),
                "     aws service-quotas request-service-quota-increase --service-code lambda \\",
                "         --quota-code %s --desired-value %d --region %s" % (LAMBDA_QUOTA_CODE, need, primary),
                "     aws service-quotas list-requested-service-quota-change-history --service-code lambda --region %s" % primary,
                "     ```", "",
                "   - Tenant Lambda functions need their own headroom on top of this; size the request for them too.", ""]
        n += 1
    if part == "aws-us-gov":
        out += ["%d. **AWS GovCloud (US) account** linked to the commercial payer; the enclave is deployed from it." % n, ""]
        n += 1
    if "hipaa" in base or "hitrust" in base:
        out += ["%d. **Accept the AWS Business Associate Addendum** (AWS Artifact → Agreements) for the enclave account "
                "or the organization before any PHI enters it." % n, ""]
        n += 1
    out += ["%d. **Organizations**: the enclave account is a member of the customer organization "
            "(`account-part-of-organizations`). The SCP/RCP bundles (`deploy_org_policies = true`, CDK "
            "`-c sgea:deployOrgPolicies=true`) are applied **from the management or delegated-administrator account**, "
            "with `org_id`, `org_target_ids` and the perimeter inputs set. Test them on a sandbox OU first." % n, ""]
    n += 1
    if scca_required(resolved):
        out += ["%d. **DoD SCCA**: DISA BCAP connection, routing of the enclave VPC through the VDSS firewall "
                "endpoints, and a TCCM are mission-owner prerequisites (SGEA emits VDSS / VDMS only)." % n, ""]
        n += 1
    if "cdk" in targets:
        out += ["%d. **CDK bootstrap** in `%s` and `%s` (`npx cdk bootstrap aws://<account>/<region>`)." % (n, primary, replica), ""]
        n += 1

    # ---------------- 2. landing-zone overlap ----------------
    out += ["## 2. Decide what the landing zone already owns", "",
            "Set these to `false` where Control Tower / LZA or an org delegated administrator already runs them "
            "(Terraform variable / CDK `-c sgea:<name>`). The control stays satisfied by the existing owner.", "",
            "| Setting | Terraform | CDK context |", "|---|---|---|",
            "| AWS Config recorder | `create_config_recorder` | `createConfigRecorder` |",
            "| GuardDuty | `create_guardduty` | `createGuardDuty` |",
            "| Security Hub | `create_securityhub` | `createSecurityHub` |",
            "| Amazon Inspector | `create_inspector` | `createInspector` |",
            "| Account baseline (EBS default encryption, snapshot / S3 public-access blocks, password policy, "
            "default SG) | `manage_account_baseline` | `manageAccountBaseline` |", ""]

    # ---------------- 3. account / identity / network prerequisites ----------------
    pre = _dispositions(root, resolved, "customer-prerequisite")
    out += ["## 3. Account, identity and network prerequisites (customer-owned)", "",
            "AWS Config rules in the composed packs that the enclave IaC does not own. Confirm each before go-live; "
            "AWS Config evaluates them continuously once the conformance packs are deployed.", "",
            "| Rule | What to confirm |", "|---|---|"] + ["| `%s` | %s |" % (r, why) for r, why in pre] + [""]

    # ---------------- 4. process controls ----------------
    proc = _dispositions(root, resolved, "process")
    if proc:
        out += ["## 4. Process controls (manual evidence)", "", "| Rule | Evidence |", "|---|---|"] + \
               ["| `%s` | %s |" % (r, why) for r, why in proc] + [""]

    # ---------------- known open findings ----------------
    import yaml
    kf = (yaml.safe_load(open(os.path.join(root, "sources", "inferred", "known-findings.yaml"))) or {}).get("findings") or []
    rules = set()
    for b in resolved["baselines"]:
        cat = json.load(open(os.path.join(root, "catalog", b + ".json")))
        rules |= {r["config_rule"] for lst in cat["services"].values() for r in lst}
    mine = [f for f in kf if f["rule"] in rules and f.get("status") == "open"]
    if mine:
        out += ["## Known open findings (expect these in AWS Config)", "",
                "Observed in SGEA's sandbox validation and **not fixed by this release**. Plan for them before your "
                "assessment: each needs the action below or a documented risk acceptance in the SSP.", ""]
        for f in mine:
            out += ["### %s — `%s` (%s)" % (f["id"], f["rule"], "enclave" if f["owner"] == "enclave" else "tenant apps"), "",
                    "- **Observed:** " + f["observed"], "- **Impact:** " + f["impact"],
                    "- **What to do:** " + f["customer_action"], ""]

    # ---------------- running cost ----------------
    lines = cost_estimate(resolved)
    out += ["## Running cost estimate (enclave only)", "",
            "On-demand list prices for us-east-1 (AWS Price List API, %s); other regions and GovCloud differ. "
            "Confirm with the AWS Pricing Calculator before quoting. Assumes 2 AZs, no traffic and no tenant apps." % PRICE_DATE, "",
            "| Fixed monthly floor | USD / month |", "|---|---|"] + \
           ["| %s | %.2f |" % (n, v) for n, v in lines] + \
           ["| **Total floor** | **%.2f** |" % sum(v for _, v in lines), "",
            "Usage-priced on top of the floor: interface endpoint data ($%.2f / GB), Aurora ACUs above the minimum "
            "($%.2f / ACU-hour) and storage ($%.2f / GB-month), Bedrock model and AgentCore usage, AWS Config "
            "($%.3f per rule evaluation, $%.3f per configuration item; the conformance packs' rule count drives this), "
            "CloudTrail data events ($%.2f per 100,000), CloudWatch Logs ingestion ($%.2f / GB) and retention, "
            "GuardDuty / Security Hub / Inspector (per-account usage pricing, unless the landing zone already pays "
            "for them), S3 log storage and cross-region replication, AWS Backup storage." % (
                VPCE_GB, AURORA_ACU_HOUR, AURORA_GB_MONTH, CONFIG_EVAL, CONFIG_ITEM, CT_DATA_EVENT * 100000, LOGS_GB), ""]

    # ---------------- 5. after the first deploy ----------------
    out += ["## %d. After the first deploy" % (5 if proc else 4), "",
            "1. Subscribe the security team to the `sgea-<env>-security-alarms` SNS topic (encrypted with the enclave CMK).",
            "2. Re-evaluate the conformance-pack rules once the deploy has finished (some periodic rules, e.g. "
            "`dynamodb-in-backup-plan`, otherwise keep a result recorded before the backup plan existed for up to 24 h): "
            "`aws configservice start-config-rules-evaluation --config-rule-names <rule ...>` (Config console: "
            "Conformance packs → Re-evaluate). Then confirm the packs report compliant and review any `runtime-only` rule "
            "(`docs/CONTROL-COVERAGE.md`).",
            "3. ISSO review of the SGEA-inferred Bedrock / AgentCore controls (`sources/inferred/service-controls.yaml`) "
            "and of the rule dispositions (`sources/inferred/rule-dispositions.yaml`).", ""]
    return "\n".join(out)
